export function getProgramById(id: string): Program | undefined {
  return PROGRAMS.find(p => p.id === id);
}

export function assignProgram(goal: string, level: string, location: string, daysPerWeek: number): string {
  if (location === 'home') return 'prog_home_dumbbell';
  if (goal === 'fat_loss') return 'prog_fat_loss';
  if (level === 'beginner') return 'prog_beginner_full_body';
  if (daysPerWeek >= 5) return 'prog_mens_physique';
  return 'prog_4day_muscle';
}
