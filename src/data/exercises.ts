export function getExerciseById(id: string): Exercise | undefined {
  return EXERCISES.find(e => e.id === id);
}

export function getExercisesByMuscle(muscle: string): Exercise[] {
  return EXERCISES.filter(
    e => e.muscleGroup === muscle || e.secondaryMuscles.some(m => m.toLowerCase() === muscle.toLowerCase())
  );
}

export function getExercisesByEquipment(equip: string[]): Exercise[] {
  if (!equip.length) return EXERCISES;
  return EXERCISES.filter(e => e.equipment.some(eq => equip.includes(eq)));
}
