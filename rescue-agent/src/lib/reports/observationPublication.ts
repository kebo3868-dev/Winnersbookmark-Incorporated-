import { analyzeJourney } from '@/lib/audit/journey';
import { detectRevenueLeaks } from '@/lib/audit/leaks';
import { calculateCategoryScores } from '@/lib/scoring/rescueScore';
import type { EvidenceRecordLike, JourneyStageResult } from '@/types/audit';
import { EVIDENCE_TEMPLATES } from './generated/evidenceTemplates';
import { isClaimFree } from './narrativePolicy';

/**
 * EVIDENCE-BACKED PUBLICATION OF CLIENT-FACING OBSERVATIONS.
 *
 * A stored audit's observation text — evidence facts and supporting context,
 * journey findings, finding titles, descriptions and impacts, score
 * explanations — was written by whichever engine version ran the audit, and
 * may since have been edited. Screening that text for bad wording kept leaking
 * ("It is a boon for the restaurant.", "represents a quantum leap", "The SIP
 * dialog orchestrator is a sound investment."), so nothing stored is published
 * because a screen judged it acceptable. Instead, every observation shown to a
 * client or a sales rep has PROVENANCE, or a neutral fallback is shown:
 *
 *  1. Evidence facts and supporting context are published only when they are
 *     an instance of an audited template the engine actually writes, bound to
 *     the evidence type it writes it with (generated/evidenceTemplates.ts,
 *     generated from the collector source and every historical engine
 *     version). The values the template interpolated (a page title, a label,
 *     a test note) must each be claim-free (narrativePolicy.isClaimFree). A
 *     supporting context that is only URLs is data. Anything else: a neutral
 *     fact, and no supporting context.
 *  2. Journey findings, finding titles, descriptions and impacts, and score
 *     explanations are not read from storage at all. They are REGENERATED by
 *     the current engine from this audit's own published evidence — the same
 *     pipeline the audit ran (analyzeJourney → detectRevenueLeaks →
 *     calculateCategoryScores) — and published only where the regenerated
 *     item matches the stored one in context: the same journey stage with the
 *     same status, the same finding category with the same validation state
 *     and overlapping evidence, the same score category with the same score.
 *     A stored item with no such match gets neutral fallback wording.
 *
 * Scores, statuses, confidence, classifications, rankings and every stored
 * record are unchanged: only the text a reader sees is chosen here. Both the
 * client report loader and the Sales Brief loader publish through this
 * module, so the web report, the PDF and the Sales Brief agree.
 */

export const NEUTRAL_FACT = 'Evidence was recorded for this check; its stored wording could not be traced to the audit engine and is not shown.';
const NEUTRAL_PROBLEM = 'The stored description of this finding could not be traced to the audit evidence and is not shown; its evidence is listed in the appendix.';
const NEUTRAL_IMPACT = 'Not measured.';
const NEUTRAL_EXPLANATION = 'See the findings for this category.';
const NEUTRAL_STAGE: Record<string, string> = {
  HEALTHY: 'No friction was observed at this stage; see the evidence in the appendix.',
  FRICTION: 'Friction was recorded at this stage; see the evidence in the appendix.',
  RISK: 'A risk was recorded at this stage; see the evidence in the appendix.',
};
const NEUTRAL_STAGE_OTHER = 'This stage could not be fully assessed from public evidence; see the appendix.';

export type Provenance = 'TEMPLATE' | 'DATA' | 'REGENERATED' | 'FALLBACK' | 'NONE';

const COMPILED = EVIDENCE_TEMPLATES.map((t) => ({ ...t, re: new RegExp(`^(?:${t.pattern})$`, 's') }));
const URL_ONLY = /^https?:\/\/\S+(?:[ ,;]+https?:\/\/\S+)*$/;

/**
 * Whether one stored evidence text is an instance of an audited template for
 * its evidence type, with every interpolated value claim-free.
 */
export function evidenceTextProvenance(evidenceType: string, field: 'fact' | 'supportingContext', text: string): Provenance {
  if (field === 'supportingContext' && URL_ONLY.test(text.trim())) return 'DATA';
  for (const t of COMPILED) {
    // Bound to the evidence type it is written with: a template whose type the
    // generator could not determine establishes no provenance.
    if (t.field !== field || !t.types || !t.types.includes(evidenceType)) continue;
    const m = t.re.exec(text);
    if (!m) continue;
    const slots = m.slice(1).filter((v): v is string => typeof v === 'string' && v.trim().length > 0);
    if (slots.every((v) => isClaimFree(v))) return 'TEMPLATE';
  }
  return 'NONE';
}

export interface StoredEvidence extends EvidenceRecordLike {
  sourceUrl: string | null;
}
export interface PublishedEvidence extends StoredEvidence {
  provenance: { fact: Provenance; supportingContext: Provenance };
}

/** One evidence record as it may be published. */
export function publishEvidence(e: StoredEvidence): PublishedEvidence {
  const fact = evidenceTextProvenance(e.evidenceType, 'fact', e.fact);
  const context = e.supportingContext === null ? 'NONE' : evidenceTextProvenance(e.evidenceType, 'supportingContext', e.supportingContext);
  return {
    ...e,
    fact: fact === 'NONE' ? NEUTRAL_FACT : e.fact,
    supportingContext: context === 'NONE' ? null : e.supportingContext,
    provenance: { fact: fact === 'NONE' ? 'FALLBACK' : fact, supportingContext: e.supportingContext === null ? 'NONE' : context === 'NONE' ? 'FALLBACK' : context },
  };
}

interface StoredStage {
  stage: string;
  status: string;
  finding: string;
  manualValidationRequired: boolean;
}
interface StoredOpportunity {
  category: string;
  title: string;
  problem: string;
  businessImpact: string;
  recommendedSolution: string;
  manualValidationRequired: boolean;
  evidenceIds: string[];
}
interface StoredScore {
  category: string;
  score: number | null;
  insufficientData: boolean;
  explanation: string;
}

export interface PublicationReport {
  evidence: { total: number; factFallbacks: number; contextOmitted: number };
  journey: { total: number; fallbacks: number };
  opportunities: { total: number; fallbacks: number };
  scores: { total: number; fallbacks: number };
}

const sentenceCase = (category: string) => category.charAt(0) + category.slice(1).toLowerCase();

/**
 * A stored audit's observations as they may be published. Every input record
 * is returned in the same order with only its text replaced; nothing else
 * (scores, statuses, ids, confidence, flags) is touched.
 */
export function publishAuditObservations<
  E extends StoredEvidence,
  J extends StoredStage,
  O extends StoredOpportunity,
  S extends StoredScore,
>(stored: { evidence: E[]; journey: J[]; opportunities: O[]; scores: S[] }): {
  evidence: (E & PublishedEvidence)[];
  journey: J[];
  opportunities: O[];
  scores: S[];
  report: PublicationReport;
} {
  const evidence = stored.evidence.map((e) => ({ ...e, ...publishEvidence(e) }));
  // The engine re-reads only evidence with provenance: a fact it cannot
  // trace is not evidence it may draw conclusions from.
  const engineEvidence: EvidenceRecordLike[] = evidence
    .filter((e) => e.provenance.fact !== 'FALLBACK')
    .map((e) => ({ id: e.id, evidenceType: e.evidenceType, fact: e.fact, supportingContext: e.supportingContext, confidence: e.confidence, sourceUrl: e.sourceUrl }));
  const ids = new Set(engineEvidence.map((e) => e.id));

  let journeyR: JourneyStageResult[] = [];
  let leaksR: ReturnType<typeof detectRevenueLeaks> = [];
  let scoresR: ReturnType<typeof calculateCategoryScores> = [];
  try {
    journeyR = analyzeJourney(engineEvidence);
    leaksR = detectRevenueLeaks({ evidence: engineEvidence, journey: journeyR });
    scoresR = calculateCategoryScores(journeyR, engineEvidence);
  } catch {
    // Regeneration failed: every regenerated item falls back below.
  }

  let journeyFallbacks = 0;
  const journey = stored.journey.map((j) => {
    const r = journeyR.find((x) => x.stage === j.stage && x.status === j.status && x.manualValidationRequired === j.manualValidationRequired);
    if (r) return { ...j, finding: r.finding };
    journeyFallbacks++;
    return { ...j, finding: NEUTRAL_STAGE[j.status] ?? NEUTRAL_STAGE_OTHER };
  });

  let oppFallbacks = 0;
  const opportunities = stored.opportunities.map((o) => {
    const r = leaksR.find(
      (x) =>
        x.category === o.category &&
        x.manualValidationRequired === o.manualValidationRequired &&
        x.evidenceIds.every((id) => ids.has(id)) &&
        (o.evidenceIds.length === 0 || x.evidenceIds.some((id) => o.evidenceIds.includes(id))),
    );
    if (r) return { ...o, title: r.title, problem: r.problem, businessImpact: r.businessImpact, recommendedSolution: r.recommendedSolution };
    oppFallbacks++;
    return { ...o, title: sentenceCase(o.category), problem: NEUTRAL_PROBLEM, businessImpact: NEUTRAL_IMPACT };
  });

  let scoreFallbacks = 0;
  const scores = stored.scores.map((s) => {
    const r = scoresR.find((x) => x.category === s.category && x.insufficientData === s.insufficientData && (x.insufficientData ? true : x.score === s.score));
    if (r) return { ...s, explanation: r.explanation };
    scoreFallbacks++;
    return { ...s, explanation: NEUTRAL_EXPLANATION };
  });

  return {
    evidence,
    journey,
    opportunities,
    scores,
    report: {
      evidence: {
        total: evidence.length,
        factFallbacks: evidence.filter((e) => e.provenance.fact === 'FALLBACK').length,
        contextOmitted: evidence.filter((e) => e.provenance.supportingContext === 'FALLBACK').length,
      },
      journey: { total: journey.length, fallbacks: journeyFallbacks },
      opportunities: { total: opportunities.length, fallbacks: oppFallbacks },
      scores: { total: scores.length, fallbacks: scoreFallbacks },
    },
  };
}
