/**
 * EVIDENCE-BACKED PUBLICATION OF CLIENT-FACING OBSERVATIONS.
 *
 * A stored audit's observation text — evidence facts and supporting context,
 * journey findings, finding titles, descriptions and impacts, score
 * explanations — and its identifiers (categories, stages, statuses, evidence
 * types) were written by whichever engine version ran the audit, and may since
 * have been edited. Nothing stored is published because a screen judged it
 * acceptable. Every observation shown to a client or a sales rep is published
 * here, with its provenance, or replaced with neutral wording:
 *
 *  1. Identifiers pass through explicit allowlists (canonicalIdentifiers.ts);
 *     an unknown one becomes a neutral sentinel with a neutral label.
 *  2. Evidence facts and supporting context must be an instance of an audited
 *     engine template bound to their evidence type — and every value the
 *     template interpolated is verified on its own (slotVerification.ts): a
 *     page title against the collected page's stored title, a URL against the
 *     collected hosts and named platforms, a label against a closed
 *     vocabulary. A fact whose frame matches but whose value cannot be
 *     verified is shown with that value replaced by "[not verified]"; a
 *     supporting context with such a value is not shown. No template: a
 *     neutral fact.
 *  3. Journey findings, finding title/problem/impact and score explanations are
 *     REGENERATED by the current engine from this audit's own published
 *     evidence, and published where the regenerated item matches the stored
 *     one in context (same stage and status; same category, validation state
 *     and evidence; same category and score).
 *  4. Where the current engine no longer writes the stored item (an audit run
 *     by an earlier engine version), the stored text itself is published only
 *     if it is verified: a journey finding or finding text must be an instance
 *     of the wording some engine version wrote for that stage and status, or
 *     that category (generated/observationTemplates.ts), with every
 *     interpolated value verified, and must pass the narrative policy; a score
 *     explanation must be the one the scoring code derives from the audit's own
 *     stored stage statuses, giving the stored score. Otherwise neutral
 *     wording that says only what the stored status records.
 *
 * Scores, statuses, confidence, classifications, rankings and every stored
 * record are unchanged: only what a reader sees is chosen here. Both the
 * client report loader and the Sales Brief loader publish through this
 * module, so the web report, the PDF and the Sales Brief agree.
 */

export const NEUTRAL_FACT = 'Evidence was recorded for this check; its stored wording could not be traced to the audit engine and is not shown.';
const NEUTRAL_PROBLEM = 'The stored description of this finding could not be traced to the audit evidence and is not shown; its evidence is listed in the appendix.';
const NEUTRAL_IMPACT = 'Not measured.';
const NEUTRAL_EXPLANATION = 'See the findings for this category.';
const NEUTRAL_STAGE: Record<string, string> = {
  HEALTHY: 'No friction was observed at this stage; see the evidence in the appendix.',
  FRICTION: 'Friction was recorded at this stage; see the evidence in the appendix.',
  RISK: 'A risk was recorded at this stage; see the evidence in the appendix.',
};
const NEUTRAL_STAGE_OTHER = 'This stage could not be fully assessed from public evidence; see the appendix.';

export type Provenance =
  | 'SOURCE_BOUND' // a template instance whose page-title value equals the collected page's stored title
  | 'TEMPLATE' // a template instance whose every value is verified data or vocabulary
  | 'REDACTED' // a template instance shown with its unverifiable values replaced
  | 'DATA' // supporting context that is only bound URLs
  | 'REGENERATED' // written now by the current engine from published evidence
  | 'HISTORICAL' // stored text verified as the wording of an earlier engine version
  | 'DERIVED' // a score explanation derived from the audit's stored stage statuses
  | 'FALLBACK' // neutral wording
  | 'NONE';

const compile = (pattern: string) => new RegExp(`^(?:${pattern})$`, 'sd');
const COMPILED = EVIDENCE_TEMPLATES.map((t) => ({ ...t, re: compile(t.pattern) }));
const COMPILED_JOURNEY = JOURNEY_TEMPLATES.map((t) => ({ ...t, re: compile(t.pattern) }));
const COMPILED_OPPORTUNITY = OPPORTUNITY_TEMPLATES.map((t) => ({ ...t, re: compile(t.pattern) }));
const URL_ONLY = /^https?:\/\/\S+(?:[ ,;]+https?:\/\/\S+)*$/;

interface TextResult {
  provenance: Provenance;
  text: string | null;
}

/**
 * One text against one template's match: the text with every unverifiable
 * value replaced, how many were replaced, and whether a value was bound to a
 * collected source.
 */
function verifiedMatch(
  m: RegExpExecArray,
  slotKind: (i: number) => ReturnType<typeof sourceSlotOf>,
  ctx: PublicationContext | undefined,
  sourceTitle: string | null,
): { text: string; redacted: number; bound: boolean } {
  const text = m[0];
  const indices = m.indices ?? [];
  let out = '';
  let cursor = 0;
  let redacted = 0;
  let bound = false;
  for (let i = 1; i < m.length; i++) {
    const span = indices[i];
    const value = m[i];
    if (!span || value === undefined) continue;
    const verdict: SlotVerdict | null = verifySlot(value, ctx, slotKind(i - 1), sourceTitle);
    if (verdict === 'SOURCE_BOUND') bound = true;
    out += text.slice(cursor, span[0]) + (verdict ? value : UNVERIFIED_VALUE);
    if (!verdict) redacted++;
    cursor = span[1];
  }
  out += text.slice(cursor);
  return { text: out, redacted, bound };
}

/** One stored evidence text, published: the best-verified instance of an audited template for its type. */
export function publishEvidenceText(
  evidenceType: string,
  field: 'fact' | 'supportingContext',
  text: string,
  ctx?: PublicationContext,
  sourceTitle: string | null = null,
): TextResult {
  if (field === 'supportingContext' && URL_ONLY.test(text.trim())) {
    const urls = text.trim().split(/[ ,;]+/).filter(Boolean);
    if (ctx && urls.every((u) => isBoundUrl(u, ctx))) return { provenance: 'DATA', text };
  }
  let best: { text: string; redacted: number; bound: boolean } | null = null;
  for (const t of COMPILED) {
    // Bound to the evidence type it is written with: a template whose type the
    // generator could not determine establishes no provenance.
    if (t.field !== field || !t.types || !t.types.includes(evidenceType)) continue;
    const m = t.re.exec(text);
    if (!m) continue;
    const r = verifiedMatch(m, (i) => sourceSlotOf(evidenceType, field, t.pattern, i), ctx, sourceTitle);
    if (!best || r.redacted < best.redacted) best = r;
  }
  if (!best) return { provenance: 'NONE', text: null };
  if (best.redacted === 0) return { provenance: best.bound ? 'SOURCE_BOUND' : 'TEMPLATE', text: best.text };
  // A supporting context with an unverifiable value is not shown at all.
  if (field === 'supportingContext') return { provenance: 'NONE', text: null };
  return { provenance: 'REDACTED', text: best.text };
}

/** The provenance of one stored evidence text (see publishEvidenceText). */
export function evidenceTextProvenance(
  evidenceType: string,
  field: 'fact' | 'supportingContext',
  text: string,
  ctx?: PublicationContext,
  sourceTitle: string | null = null,
): Provenance {
  return publishEvidenceText(evidenceType, field, text, ctx, sourceTitle).provenance;
}

export interface StoredEvidence extends EvidenceRecordLike {
  sourceUrl: string | null;
  auditSourceId?: string | null;
}
export interface PublishedEvidence extends StoredEvidence {
  provenance: { fact: Provenance; supportingContext: Provenance };
}

/** One evidence record as it may be published. */
export function publishEvidence(e: StoredEvidence, ctx?: PublicationContext): PublishedEvidence {
  const evidenceType = canonicalEvidenceType(e.evidenceType);
  const sourceTitle = ctx && e.auditSourceId ? ctx.sources.find((s) => s.id === e.auditSourceId)?.pageTitle ?? null : null;
  const fact = publishEvidenceText(evidenceType, 'fact', e.fact, ctx, sourceTitle);
  const context = e.supportingContext === null ? null : publishEvidenceText(evidenceType, 'supportingContext', e.supportingContext, ctx, sourceTitle);
  return {
    ...e,
    evidenceType,
    fact: fact.text ?? NEUTRAL_FACT,
    supportingContext: context?.text ?? null,
    // A link is shown only to a collected page of this audit, or another page of the same site.
    sourceUrl: e.sourceUrl && ctx && isLinkableUrl(e.sourceUrl, ctx) ? e.sourceUrl : null,
    provenance: {
      fact: fact.text === null ? 'FALLBACK' : fact.provenance,
      supportingContext: e.supportingContext === null ? 'NONE' : context?.text == null ? 'FALLBACK' : context.provenance,
    },
  };
}

/**
 * Stored prose (a journey finding or a finding's text) verified against the
 * wording earlier engine versions wrote under the same identifiers: the whole
 * text must be an instance with every value verified, and pass the policy.
 */
function historicalText(templates: { re: RegExp }[], text: string, ctx: PublicationContext | undefined): string | null {
  if (!assessNarrative(text).safe) return null;
  for (const t of templates) {
    const m = t.re.exec(text);
    if (m && verifiedMatch(m, () => null, ctx, null).redacted === 0) return text;
  }
  return null;
}

interface StoredStage {
  stage: string;
  status: string;
  finding: string;
  manualValidationRequired: boolean;
  confidence?: number;
  evidenceIds?: string[];
}
interface StoredOpportunity {
  category: string;
  title: string;
  problem: string;
  businessImpact: string;
  recommendedSolution: string;
  manualValidationRequired: boolean;
  evidenceIds: string[];
  customerJourneyStage?: string;
}
interface StoredScore {
  category: string;
  score: number | null;
  insufficientData: boolean;
  explanation: string;
}

export interface PublicationReport {
  evidence: { total: number; factFallbacks: number; factsRedacted: number; contextOmitted: number; linksRemoved: number };
  journey: { total: number; fallbacks: number; historical: number };
  opportunities: { total: number; fallbacks: number; historicalFields: number };
  scores: { total: number; fallbacks: number; derived: number };
  identifiers: { unrecognised: number };
}

/**
 * A stored audit's observations as they may be published. Every input record
 * is returned in the same order with only its text and identifiers replaced;
 * nothing else (scores, ids, confidence, flags, numbers) is touched.
 */
export function publishAuditObservations<
  E extends StoredEvidence,
  J extends StoredStage,
  O extends StoredOpportunity,
  S extends StoredScore,
>(stored: { evidence: E[]; journey: J[]; opportunities: O[]; scores: S[]; context?: PublicationContext }): {
  evidence: (E & PublishedEvidence)[];
  journey: J[];
  opportunities: O[];
  scores: S[];
  report: PublicationReport;
} {
  const ctx = stored.context;
  let unrecognised = 0;
  const canon = (value: string, canonical: string) => {
    if (value !== canonical) unrecognised++;
    return canonical;
  };

  const evidence = stored.evidence.map((e) => {
    canon(e.evidenceType, canonicalEvidenceType(e.evidenceType));
    return { ...e, ...publishEvidence(e, ctx) };
  });
  // The engine re-reads only evidence with provenance, as published: a fact
  // it cannot trace is not evidence it may draw conclusions from, and a value
  // that could not be verified is not one it may quote.
  const engineEvidence: EvidenceRecordLike[] = evidence
    .filter((e) => e.provenance.fact !== 'FALLBACK')
    .map((e) => ({ id: e.id, evidenceType: e.evidenceType, fact: e.fact, supportingContext: e.supportingContext, confidence: e.confidence, sourceUrl: e.sourceUrl }));
  const ids = new Set(engineEvidence.map((e) => e.id));

  let journeyR: JourneyStageResult[] = [];
  let leaksR: ReturnType<typeof detectRevenueLeaks> = [];
  let scoresR: ReturnType<typeof calculateCategoryScores> = [];
  try {
    journeyR = analyzeJourney(engineEvidence);
    leaksR = detectRevenueLeaks({ evidence: engineEvidence, journey: journeyR });
    scoresR = calculateCategoryScores(journeyR, engineEvidence);
  } catch {
    // Regeneration failed: every regenerated item falls back below.
  }

  let journeyFallbacks = 0;
  let journeyHistorical = 0;
  const journey = stored.journey.map((j) => {
    const stage = canon(j.stage, canonicalStage(j.stage));
    const status = canon(j.status, canonicalStatus(j.status));
    const r = journeyR.find((x) => x.stage === stage && x.status === status && x.manualValidationRequired === j.manualValidationRequired);
    if (r) return { ...j, stage, status, finding: r.finding };
    const historical = historicalText(COMPILED_JOURNEY.filter((t) => t.stages.includes(stage) && t.statuses.includes(status)), j.finding, ctx);
    if (historical) {
      journeyHistorical++;
      return { ...j, stage, status, finding: historical };
    }
    journeyFallbacks++;
    return { ...j, stage, status, finding: NEUTRAL_STAGE[status] ?? NEUTRAL_STAGE_OTHER };
  });

  let oppFallbacks = 0;
  let oppHistorical = 0;
  const opportunities = stored.opportunities.map((o) => {
    const category = canon(o.category, canonicalFindingCategory(o.category));
    const ident =
      o.customerJourneyStage === undefined
        ? { category }
        : { category, customerJourneyStage: canon(o.customerJourneyStage, canonicalStage(o.customerJourneyStage)) };
    const r = leaksR.find(
      (x) =>
        x.category === category &&
        x.manualValidationRequired === o.manualValidationRequired &&
        x.evidenceIds.every((id) => ids.has(id)) &&
        (o.evidenceIds.length === 0 || x.evidenceIds.some((id) => o.evidenceIds.includes(id))),
    );
    if (r) return { ...o, ...ident, title: r.title, problem: r.problem, businessImpact: r.businessImpact, recommendedSolution: r.recommendedSolution };
    oppFallbacks++;
    const fieldText = (field: 'title' | 'problem' | 'businessImpact', neutral: string) => {
      const h = historicalText(COMPILED_OPPORTUNITY.filter((t) => t.field === field && t.categories.includes(category)), o[field], ctx);
      if (h) oppHistorical++;
      return h ?? neutral;
    };
    return {
      ...o,
      ...ident,
      title: fieldText('title', neutralFindingTitle(category)),
      problem: fieldText('problem', NEUTRAL_PROBLEM),
      businessImpact: fieldText('businessImpact', NEUTRAL_IMPACT),
    };
  });

  // A score explanation the current engine no longer gives for this score may
  // still be the one the scoring code derives from the audit's own STORED stage
  // statuses — the statuses the stored score was computed from.
  let storedDerived: ReturnType<typeof calculateCategoryScores> = [];
  try {
    storedDerived = calculateCategoryScores(
      journey.map((j) => ({
        stage: j.stage as JourneyStageResult['stage'],
        status: j.status as JourneyStageResult['status'],
        finding: j.finding,
        confidence: j.confidence ?? 0,
        manualValidationRequired: j.manualValidationRequired,
        evidenceIds: j.evidenceIds ?? [],
      })),
      engineEvidence,
    );
  } catch {
    storedDerived = [];
  }
  let scoreFallbacks = 0;
  let scoreDerived = 0;
  const sameScore = (x: { insufficientData: boolean; score: number | null }, s: StoredScore) =>
    x.insufficientData === s.insufficientData && (x.insufficientData ? true : x.score === s.score);
  const scores = stored.scores.map((s) => {
    const category = canon(s.category, canonicalScoreCategory(s.category));
    const r = scoresR.find((x) => x.category === category && sameScore(x, s));
    if (r) return { ...s, category, explanation: r.explanation };
    const d = storedDerived.find((x) => x.category === category && sameScore(x, s));
    if (d) {
      scoreDerived++;
      return { ...s, category, explanation: d.explanation };
    }
    scoreFallbacks++;
    return { ...s, category, explanation: NEUTRAL_EXPLANATION };
  });

  return {
    evidence,
    journey,
    opportunities,
    scores,
    report: {
      evidence: {
        total: evidence.length,
        factFallbacks: evidence.filter((e) => e.provenance.fact === 'FALLBACK').length,
        factsRedacted: evidence.filter((e) => e.provenance.fact === 'REDACTED').length,
        contextOmitted: evidence.filter((e) => e.provenance.supportingContext === 'FALLBACK').length,
        linksRemoved: evidence.filter((e, i) => stored.evidence[i].sourceUrl && !e.sourceUrl).length,
      },
      journey: { total: journey.length, fallbacks: journeyFallbacks, historical: journeyHistorical },
      opportunities: { total: opportunities.length, fallbacks: oppFallbacks, historicalFields: oppHistorical },
      scores: { total: scores.length, fallbacks: scoreFallbacks, derived: scoreDerived },
      identifiers: { unrecognised },
    },
  };
}
