// Runs only against a fresh disposable local database named review or review_image.
// Start the local app with FRONTDESK_PUBLIC_ENDPOINT_ENABLED=true; never use production.
import assert from 'node:assert/strict';
import { createHash, randomBytes, scryptSync } from 'node:crypto';
import { createRequire } from 'node:module';
const base = new URL(process.env.REVIEW_BASE_URL);
const database = new URL(process.env.DATABASE_URL);
assert(['127.0.0.1', 'localhost'].includes(base.hostname), 'Local API only');
assert(['127.0.0.1', 'localhost'].includes(database.hostname), 'Disposable local database only');
assert(['/review', '/review_image'].includes(database.pathname));
const require = createRequire(new URL('../../rescue-agent/package.json', import.meta.url));
const { PrismaClient } = require('@prisma/client');
const db = new PrismaClient();
const run = randomBytes(6).toString('hex');
const password = 'local-verification-password';
const salt = randomBytes(16);
const hash = ['scrypt', 16384, 8, 1, salt.toString('base64url'), scryptSync(password, salt, 32, { N: 16384, r: 8, p: 1 }).toString('base64url')].join('$');
const post = (path, body, headers = {}) => fetch(new URL(path, base), { method: 'POST', headers: { 'content-type': 'application/json', ...headers }, body: JSON.stringify(body) });
try {
 const config = { restaurantName: 'Local verification fixture', pilot: { ownerVerifiedAt: '2026-11-03T12:30Z', telecomAttestedAt: '2026-11-03T12:30:00Z', failureReviewAttestedAt: '2026-11-03T12:30Z' } };
 const tenants = await Promise.all([0,1].map(i => db.fdTenant.create({data:{slug:`review-${run}-${i}`, name: 'Local verification fixture', status:'ACTIVE', config}})));
 const tenant = tenants[0];
 const path = `/api/frontdesk/${tenant.slug}/message`;
 const unsigned = await Promise.all(Array.from({length:40},()=>post(path,{message:'hello'})));
 assert(unsigned.every(r=>r.status===401));
 assert.equal(await db.fdAuditLog.count({where:{tenantId:tenant.id}}),0);
 assert.equal(await db.fdFailure.count({where:{tenantId:tenant.id}}),0);
 const forged = await Promise.all(Array.from({length:40},(_,i)=>post(path,{message:'hello'},{authorization:`Bearer wbifd_${run}_${String(i).padStart(20,'x')}`,'x-request-id':`request-${i}`})));
 assert(forged.every(r=>r.status===401));
 const failures = await db.fdFailure.findMany({where:{tenantId:tenant.id}});
 assert.equal(failures.length,1); assert.equal(failures[0].attempts,40);
 assert.equal(await db.fdAuditLog.count({where:{tenantId:tenant.id}}),0);
 console.log('PASS: 40 unsigned requests write nothing; 40 concurrent varied forged keys produce one failure row with count 40, no audit rows. Minute-precision tenant resolves, without 404.');
 const key = `wbifd_${randomBytes(24).toString('hex')}`;
 await db.fdApiKey.create({data:{tenantId:tenant.id,name:'Local review',prefix:key.slice(0,12),keyHash:createHash('sha256').update(key).digest('hex'),scopes:['message:write']}});
 assert.equal((await post(`/api/frontdesk/${tenants[1].slug}/message`,{message:'hello'},{authorization:`Bearer ${key}`})).status,401);
 const handled = await post(path,{message:'hello'},{authorization:`Bearer ${key}`});
 assert.equal(handled.status,200,await handled.text());
 assert.equal(await db.fdAuditLog.count({where:{tenantId:tenant.id,event:'MESSAGE_HANDLED',outcome:'ALLOWED'}}),1);
 console.log('PASS: authenticated message succeeds and remains audited; tenant key cannot reach another tenant.');
 const admins = await Promise.all([0,1].map(i=>db.fdUser.create({data:{tenantId:null,email:`review-admin-${run}-${i}@example.invalid`,passwordHash:hash,role:'WBI_ADMIN'}})));
 const login=(user,pass,slug)=>post('/api/frontdesk/auth/login',{email:user,password:pass,...(slug?{tenantSlug:slug}:{})});
 assert.equal((await login(admins[0].email,password)).status,200);
 const sessionCount=await db.fdSession.count({where:{userId:admins[0].id}});
 for(let i=0;i<10;i++)assert.equal((await login(i%2?` ${admins[0].email.toUpperCase()} `:admins[0].email,'wrong')).status,401);
 const locked=await login(admins[0].email,password); assert.equal(locked.status,401); assert.equal(locked.headers.get('set-cookie'),null);
 assert.equal(await db.fdSession.count({where:{userId:admins[0].id}}),sessionCount);
 assert.equal((await db.fdAdminLoginCounter.findFirst({where:{subject:admins[0].id}})).count,10);
 assert.equal((await login(admins[1].email,password)).status,200);
 const unknowns=await Promise.all(Array.from({length:25},(_,i)=>login(`missing-${run}-${i}@example.invalid`,'wrong')));
 assert(unknowns.every(r=>r.status===401));
 const unknownRows=await db.fdAdminLoginCounter.findMany({where:{subject:'__unknown_account__'}});
 assert.equal(unknownRows.length,1);assert.equal(unknownRows[0].count,25);
 console.log('PASS: admin lockout at 10 failures, canonical account key, no refused session, unrelated admin unaffected; 25 concurrent unknown addresses share one durable counter.');
 const staff = await Promise.all(tenants.map(t=>db.fdUser.create({data:{tenantId:t.id,email:`review-staff-${run}@example.invalid`,passwordHash:hash,role:'RESTAURANT_OWNER'}})));
 for(let i=0;i<10;i++)assert.equal((await login(staff[0].email,'wrong',tenants[0].slug)).status,401);
 assert.equal((await login(staff[0].email,password,tenants[0].slug)).status,401);
 assert.equal(await db.fdSession.count({where:{userId:staff[0].id}}),0);
 assert.equal((await login(staff[1].email,password,tenants[1].slug)).status,200);
 console.log('PASS: identical tenant lockout policy, no refused session, same email at another tenant remains isolated.');
} finally { await db.$disconnect(); }
